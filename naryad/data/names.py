"""Вымышленные ФИО водителей. Совпадения с реальными людьми случайны."""

from __future__ import annotations

import random

# Только фамилии на -ов/-ев/-ин: у них простая женская форма.
SURNAMES = [
    "Иванов", "Смирнов", "Кузнецов", "Попов", "Васильев", "Петров",
    "Соколов", "Михайлов", "Новиков", "Фёдоров", "Морозов", "Волков",
    "Алексеев", "Лебедев", "Семёнов", "Егоров", "Павлов", "Козлов",
    "Степанов", "Николаев", "Орлов", "Андреев", "Макаров", "Никитин",
    "Захаров", "Зайцев", "Соловьёв", "Борисов", "Яковлев", "Григорьев",
    "Романов", "Воробьёв", "Сергеев", "Фролов", "Александров", "Дмитриев",
    "Королёв", "Гусев", "Киселёв", "Ильин", "Максимов", "Поляков",
    "Сорокин", "Виноградов", "Ковалёв", "Белов", "Медведев", "Антонов",
]

MALE_NAMES = [
    "Александр", "Сергей", "Андрей", "Дмитрий", "Алексей", "Михаил",
    "Николай", "Владимир", "Игорь", "Евгений", "Олег", "Павел", "Виктор",
    "Юрий", "Роман", "Максим", "Денис", "Артём", "Константин", "Иван",
]
FEMALE_NAMES = [
    "Елена", "Ольга", "Наталья", "Татьяна", "Ирина", "Светлана",
    "Марина", "Анна", "Юлия", "Галина",
]
# (мужское отчество, женское отчество)
PATRONYMICS = [
    ("Александрович", "Александровна"), ("Сергеевич", "Сергеевна"),
    ("Андреевич", "Андреевна"), ("Дмитриевич", "Дмитриевна"),
    ("Алексеевич", "Алексеевна"), ("Михайлович", "Михайловна"),
    ("Николаевич", "Николаевна"), ("Владимирович", "Владимировна"),
    ("Игоревич", "Игоревна"), ("Викторович", "Викторовна"),
    ("Юрьевич", "Юрьевна"), ("Павлович", "Павловна"),
    ("Иванович", "Ивановна"), ("Петрович", "Петровна"),
]

FEMALE_SHARE = 0.1


def full_name(rng: random.Random) -> str:
    surname = rng.choice(SURNAMES)
    male, female = rng.choice(PATRONYMICS)
    if rng.random() < FEMALE_SHARE:
        return f"{surname}а {rng.choice(FEMALE_NAMES)} {female}"
    return f"{surname} {rng.choice(MALE_NAMES)} {male}"
